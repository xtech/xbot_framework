package main

// Generates xbot/message_type_generated.go from the C++ header, so the Go message types
// cannot drift away from include/xbot/datatypes/XbotHeader.hpp. The header is the single
// source of truth for the wire protocol; this generator is what CI runs, which is why a
// developer can add a message type without installing Go.

import (
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
)

var (
	enumBlock = regexp.MustCompile(`(?s)enum class MessageType[^{]*\{(.*?)\}`)
	enumEntry = regexp.MustCompile(`(\w+)\s*=\s*(0x[0-9A-Fa-f]+)`)
)

// initialisms stay upper case in Go names (MsgRPCCall, not MsgRpcCall).
var initialisms = map[string]bool{
	"API": true, "CBOR": true, "ID": true, "IO": true, "JSON": true,
	"RPC": true, "TCP": true, "UDP": true, "URL": true,
}

func goName(symbol string) string {
	var b strings.Builder
	b.WriteString("Msg")
	for _, part := range strings.Split(symbol, "_") {
		if part == "" {
			continue
		}
		if initialisms[part] {
			b.WriteString(part)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(strings.ToLower(part[1:]))
	}
	return b.String()
}

func generateMessageTypes(headerPath, outPath string) error {
	src, err := os.ReadFile(headerPath)
	if err != nil {
		return err
	}
	block := enumBlock.FindSubmatch(src)
	if block == nil {
		return fmt.Errorf("%s: enum class MessageType not found - the header format changed", headerPath)
	}
	entries := enumEntry.FindAllSubmatch(block[1], -1)
	if len(entries) == 0 {
		return fmt.Errorf("%s: no enumerators found in enum class MessageType", headerPath)
	}

	type entry struct {
		symbol string
		goName string
		value  string
	}
	var all []entry
	for _, m := range entries {
		symbol := string(m[1])
		all = append(all, entry{symbol: symbol, goName: goName(symbol), value: string(m[2])})
	}

	// Align the const block like gofmt would.
	width := 0
	for _, e := range all {
		if len(e.goName) > width {
			width = len(e.goName)
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by 'go generate' (xbot-codegen -message-types) from\n")
	b.WriteString("// include/xbot/datatypes/XbotHeader.hpp. DO NOT EDIT.\n\n")
	b.WriteString("package xbot\n\n")
	b.WriteString("import \"fmt\"\n\n")
	b.WriteString("// MessageType is the 8 bit message type of an XbotHeader\n")
	b.WriteString("// (see include/xbot/datatypes/XbotHeader.hpp).\n")
	b.WriteString("//\n")
	b.WriteString("// The first bit of the value tells how the payload is encoded: 0 = raw binary\n")
	b.WriteString("// (DATA, RPC, CLAIM, ...), 1 = CBOR (service discovery).\n")
	b.WriteString("type MessageType uint8\n\n")
	b.WriteString("// Message types, generated from the C++ header.\nconst (\n")
	for _, e := range all {
		fmt.Fprintf(&b, "\t%-*s MessageType = %s\n", width, e.goName, e.value)
	}
	b.WriteString(")\n\n")
	b.WriteString("// messageTypeNames is the wire symbol of every message type.\n")
	b.WriteString("var messageTypeNames = map[MessageType]string{\n")
	for _, e := range all {
		fmt.Fprintf(&b, "\t%-*s %q,\n", width, e.goName+":", e.symbol)
	}
	b.WriteString("}\n\n")
	b.WriteString("// String returns the symbol of the message type, e.g. \"RPC_CALL\".\n")
	b.WriteString("func (m MessageType) String() string {\n")
	b.WriteString("\tif name, ok := messageTypeNames[m]; ok {\n\t\treturn name\n\t}\n")
	b.WriteString("\treturn fmt.Sprintf(\"MessageType(0x%02x)\", uint8(m))\n}\n")

	// go/format instead of hand alignment: the result is gofmt-clean by construction,
	// which is what the CI format check expects right after a regeneration.
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting the generated code: %w", err)
	}
	if outPath == "" {
		_, err = os.Stdout.Write(formatted)
		return err
	}
	if err = os.WriteFile(outPath, formatted, 0o644); err != nil {
		return err
	}
	names := make([]string, 0, len(all))
	for _, e := range all {
		names = append(names, e.symbol)
	}
	sort.Strings(names)
	fmt.Printf("wrote %s (%d message types)\n", outPath, len(names))
	return nil
}
