package codegen

import (
	"fmt"
	"strings"
)

// schemaRef appends the name as written in the service.json when it differs from
// the generated Go name, so the schema stays the reference a reader greps for.
func schemaRef(raw, goName string) string {
	if raw == goName {
		return ""
	}
	return fmt.Sprintf(" (%q in the service.json)", raw)
}

// run emits the whole file: header, ids, enums, the Client, one method per RPC
// function, register setters, input senders and the wire helpers.
func (g *generator) run() error {
	s := g.schema

	g.line("// Code generated by xbot-codegen from the service.json. DO NOT EDIT.")
	g.line("//")
	g.line("// Regenerate with:")
	g.line("//")
	g.line("//\txbot-codegen -service <service.json> [-service-id <id>] -out <file>.go")
	g.line("")
	g.f("// Package %s is a client for the %s service (service.json version %d).",
		g.opts.Package, s.Type, s.Version)
	g.f("package %s", g.opts.Package)
	g.line("")
	g.line(`import (
	"context"
	"encoding/binary"
	"fmt"
	"math"

	"github.com/xtech/xbot_framework/xbot_service_interface_go/xbot"
)`)
	g.line("")

	if g.opts.ServiceID != 0 {
		g.f("// ServiceID is the id of the %s service (service_ids.h).", s.Type)
		g.f("const ServiceID uint16 = %d", g.opts.ServiceID)
		g.line("")
	}

	g.line(`// Function ids (service.json -> "functions").`)
	g.line("const (")
	for _, fn := range s.Functions {
		g.f("\tFn%s uint8 = %d", goName(fn.Name), fn.ID)
	}
	g.line(")")
	g.line("")

	for _, e := range s.Enums {
		if err := g.emitEnum(e); err != nil {
			return err
		}
	}

	g.line("// Client is a client for the " + s.Type + " service.")
	g.line("type Client struct{ conn *xbot.Conn }")
	g.line("")
	g.line("// Dial connects to the service; it claims it unless opts.NoClaim is set.")
	if g.opts.ServiceID != 0 {
		g.line("func Dial(ctx context.Context, opts xbot.Options) (*Client, error) {")
		g.line("\topts.ServiceID = ServiceID")
	} else {
		g.line("func Dial(ctx context.Context, serviceID uint16, opts xbot.Options) (*Client, error) {")
		g.line("\topts.ServiceID = serviceID")
	}
	g.f("\topts.ExpectType = %q", s.Type)
	g.f("\topts.ExpectVersion = %d", s.Version)
	g.line("\tconn, err := xbot.Dial(ctx, opts)")
	g.line("\tif err != nil {")
	g.line("\t\treturn nil, err")
	g.line("\t}")
	g.line("\treturn &Client{conn: conn}, nil")
	g.line("}")
	g.line("")
	g.line("// Close closes the connection.")
	g.line("func (c *Client) Close() error { return c.conn.Close() }")
	g.line("")
	g.line("// Endpoint returns the \"ip:port\" of the service.")
	g.line("func (c *Client) Endpoint() string { return c.conn.Endpoint() }")
	g.line("")

	for _, fn := range s.Functions {
		if err := g.emitFunction(fn); err != nil {
			return err
		}
	}
	for _, r := range s.Registers {
		if err := g.emitRegister(r); err != nil {
			return err
		}
	}
	for _, in := range s.Inputs {
		if err := g.emitInput(in); err != nil {
			return err
		}
	}
	if len(s.Outputs) > 0 {
		g.f("// The service has %d outputs; receiving them needs a receive loop in", len(s.Outputs))
		g.line("// xbot.Conn, which this client does not have yet.")
		g.line("")
	}
	g.emitHelpers()
	return nil
}

// emitEnum writes the type, its constants and (optionally) the String method.
func (g *generator) emitEnum(e Enum) error {
	base, ok := goTypes[e.BaseType]
	if !ok {
		return fmt.Errorf("go codegen: enum %s: unknown base_type %q", e.ID, e.BaseType)
	}
	typeName := goName(e.ID)
	if e.ID != typeName {
		g.f("// %s is the service.json enum %q.", typeName, e.ID)
	} else {
		g.f("// %s values (service.json -> \"enums\").", typeName)
	}
	g.f("type %s %s", typeName, base)
	g.line("")
	g.line("const (")
	for _, name := range sortedEnumValues(e) {
		lit := fmt.Sprintf("%d", e.Values[name])
		if e.Bitmask {
			lit = "1 << " + lit
		}
		constName := goName(name)
		line := fmt.Sprintf("\t%s%s %s = %s", typeName, constName, typeName, lit)
		if constName != name {
			// keep the value name of the service.json next to the constant
			line += " // " + name
		}
		g.line(line)
	}
	g.line(")")
	g.line("")
	if !e.ToString {
		return nil
	}
	g.line("// String returns the name of the value.")
	g.f("func (v %s) String() string {", typeName)
	g.line("\tswitch v {")
	seen := map[int64]bool{}
	for _, name := range sortedEnumValues(e) {
		if seen[e.Values[name]] {
			continue
		}
		seen[e.Values[name]] = true
		g.f("\tcase %s%s:", typeName, goName(name))
		g.f("\t\treturn %q", strings.ToLower(name))
	}
	g.line("\t}")
	g.line("\treturn \"\"")
	g.line("}")
	g.line("")
	return nil
}

// emitFunction writes one RPC method.
func (g *generator) emitFunction(fn Function) error {
	name := goName(fn.Name)
	sig := []string{"ctx context.Context"}
	var args []string
	for _, p := range fn.Parameters {
		pname := goName(p.Name)
		where := "parameter " + pname + " of " + name
		gt, err := g.goType(p.Type, where)
		if err != nil {
			return err
		}
		expr, err := g.packExpr(p.Type, pname, where)
		if err != nil {
			return err
		}
		sig = append(sig, pname+" "+gt)
		args = append(args, fmt.Sprintf("\t\txbot.Bytes(%d, %s),", p.ID, expr))
	}
	retType, lines, err := g.decodeReturn(fn.ReturnType, name)
	if err != nil {
		return err
	}
	ret := "error"
	if retType != "" {
		ret = "(" + retType + ", error)"
	}

	g.f("// %s calls the RPC function %d%s.", name, fn.ID, schemaRef(fn.Name, name))
	g.f("func (c *Client) %s(%s) %s {", name, strings.Join(sig, ", "), ret)
	assign := "\tpayload, err := "
	if retType == "" {
		assign = "\t_, err := "
	}
	if len(args) > 0 {
		g.f("%sc.conn.Call(ctx, Fn%s,", assign, name)
		for _, a := range args {
			g.line(a)
		}
		g.line("\t)")
	} else {
		g.f("%sc.conn.Call(ctx, Fn%s)", assign, name)
	}
	if retType == "" {
		g.line("\treturn err")
	} else {
		g.line("\tif err != nil {")
		g.f("\t\treturn %s, err", zeroValue(retType))
		g.line("\t}")
		for _, l := range lines {
			g.line(strings.Replace(l, "ZERO", zeroValue(retType), 1))
		}
	}
	g.line("}")
	g.line("")
	return nil
}

// emitRegister writes a setter that sends the register as a configuration
// transaction (the service reconfigures and persists it).
func (g *generator) emitRegister(r Field) error {
	name := goName(r.Name)
	where := "register " + name
	gt, err := g.goType(r.Type, where)
	if err != nil {
		return err
	}
	expr, err := g.packExpr(r.Type, name, where)
	if err != nil {
		return err
	}
	g.f("// Set%s writes the register %d%s as a configuration transaction.",
		name, r.ID, schemaRef(r.Name, name))
	g.f("func (c *Client) Set%s(%s %s) error {", name, name, gt)
	g.f("\treturn c.conn.SendTransaction(true, xbot.Data{ID: %d, Data: %s})", r.ID, expr)
	g.line("}")
	g.line("")
	return nil
}

// emitInput writes an input sender.
func (g *generator) emitInput(in Field) error {
	name := goName(in.Name)
	where := "input " + name
	gt, err := g.goType(in.Type, where)
	if err != nil {
		return err
	}
	expr, err := g.packExpr(in.Type, name, where)
	if err != nil {
		return err
	}
	g.f("// Send%s sends the input %d%s.", name, in.ID, schemaRef(in.Name, name))
	g.f("func (c *Client) Send%s(%s %s) error {", name, name, gt)
	g.f("\treturn c.conn.SendData(%d, %s)", in.ID, expr)
	g.line("}")
	g.line("")
	return nil
}

// emitHelpers writes the wire helpers. They are always emitted, so the import
// list of the generated file never depends on the schema.
func (g *generator) emitHelpers() {
	g.line("// ---- wire helpers ----------------------------------------------------------")
	g.line("")
	g.line("func leUint8(v uint8) []byte { return []byte{v} }")
	g.line("func leUint16(v uint16) []byte { b := make([]byte, 2); binary.LittleEndian.PutUint16(b, v); return b }")
	g.line("func leUint32(v uint32) []byte { b := make([]byte, 4); binary.LittleEndian.PutUint32(b, v); return b }")
	g.line("func leUint64(v uint64) []byte { b := make([]byte, 8); binary.LittleEndian.PutUint64(b, v); return b }")
	g.line("func leInt8(v int8) []byte { return []byte{uint8(v)} }")
	g.line("func leInt16(v int16) []byte { return leUint16(uint16(v)) }")
	g.line("func leInt32(v int32) []byte { return leUint32(uint32(v)) }")
	g.line("func leInt64(v int64) []byte { return leUint64(uint64(v)) }")
	g.line("func leFloat32(v float32) []byte { return leUint32(math.Float32bits(v)) }")
	g.line("func leFloat64(v float64) []byte { return leUint64(math.Float64bits(v)) }")
	g.line("")
	g.line("// byteParam pads b with NUL to the fixed size of a T[n] parameter (n <= 0: as is).")
	g.line("func byteParam(b []byte, n int) []byte {")
	g.line("\tif n <= 0 || len(b) >= n {")
	g.line("\t\treturn b")
	g.line("\t}")
	g.line("\treturn append(b, make([]byte, n-len(b))...)")
	g.line("}")
	g.line("")
	g.line("// charParam pads s with NUL to the size of a char[n] parameter (n <= 0: as is).")
	g.line("func charParam(s string, n int) []byte { return byteParam([]byte(s), n) }")
	g.line("")
	g.line("// charValue trims the NUL padding of a char[n] value.")
	g.line("func charValue(b []byte) string {")
	g.line("\tfor len(b) > 0 && b[len(b)-1] == 0 {")
	g.line("\t\tb = b[:len(b)-1]")
	g.line("\t}")
	g.line("\treturn string(b)")
	g.line("}")
	g.line("")
	g.line("// errf prefixes an error of this client.")
	g.line("func errf(format string, args ...any) error {")
	g.f("\treturn fmt.Errorf(%q+format, args...)", g.opts.Package+": ")
	g.line("}")
	g.line("")
	g.emitSliceHelpers()
}

// sliceHelper describes the code of one numeric array helper.
type sliceHelper struct {
	goType string
	size   int
	put    string
	get    string
}

var sliceHelpers = map[string]sliceHelper{
	"Uint16":  {"uint16", 2, "binary.LittleEndian.PutUint16(b[i*2:], x)", "binary.LittleEndian.Uint16(b[i*2:])"},
	"Uint32":  {"uint32", 4, "binary.LittleEndian.PutUint32(b[i*4:], x)", "binary.LittleEndian.Uint32(b[i*4:])"},
	"Uint64":  {"uint64", 8, "binary.LittleEndian.PutUint64(b[i*8:], x)", "binary.LittleEndian.Uint64(b[i*8:])"},
	"Int8":    {"int8", 1, "b[i] = uint8(x)", "int8(b[i])"},
	"Int16":   {"int16", 2, "binary.LittleEndian.PutUint16(b[i*2:], uint16(x))", "int16(binary.LittleEndian.Uint16(b[i*2:]))"},
	"Int32":   {"int32", 4, "binary.LittleEndian.PutUint32(b[i*4:], uint32(x))", "int32(binary.LittleEndian.Uint32(b[i*4:]))"},
	"Int64":   {"int64", 8, "binary.LittleEndian.PutUint64(b[i*8:], uint64(x))", "int64(binary.LittleEndian.Uint64(b[i*8:]))"},
	"Float32": {"float32", 4, "binary.LittleEndian.PutUint32(b[i*4:], math.Float32bits(x))", "math.Float32frombits(binary.LittleEndian.Uint32(b[i*4:]))"},
	"Float64": {"float64", 8, "binary.LittleEndian.PutUint64(b[i*8:], math.Float64bits(x))", "math.Float64frombits(binary.LittleEndian.Uint64(b[i*8:]))"},
}

// sliceHelperOrder is the deterministic emission order.
var sliceHelperOrder = []string{
	"Uint16", "Uint32", "Uint64", "Int8", "Int16", "Int32", "Int64", "Float32", "Float64",
}

// emitSliceHelpers writes the numeric array helpers the schema needs: a fixed
// size T[n] is padded to n elements before encoding, and a return value is
// decoded from exactly n elements.
func (g *generator) emitSliceHelpers() {
	for _, kind := range sliceHelperOrder {
		if !g.needs[kind] {
			continue
		}
		h := sliceHelpers[kind]
		g.f("func pad%sSlice(v []%s, n int) []%s {", kind, h.goType, h.goType)
		g.line("\tif n <= 0 || len(v) >= n {")
		g.line("\t\treturn v")
		g.line("\t}")
		g.f("\tout := make([]%s, n)", h.goType)
		g.line("\tcopy(out, v)")
		g.line("\treturn out")
		g.line("}")
		g.line("")
		g.f("func le%sSlice(v []%s, n int) []byte {", kind, h.goType)
		g.f("\tv = pad%sSlice(v, n)", kind)
		g.f("\tb := make([]byte, len(v)*%d)", h.size)
		g.line("\tfor i, x := range v {")
		g.f("\t\t%s", h.put)
		g.line("\t}")
		g.line("\treturn b")
		g.line("}")
		g.line("")
		g.f("func read%sSlice(b []byte, n int) ([]%s, error) {", kind, h.goType)
		g.f("\tif n <= 0 || len(b) < n*%d {", h.size)
		g.f("\t\treturn nil, errf(\"array of %d elements: got %%d bytes, want %%d\", len(b), n*%d)", h.size, h.size)
		g.line("\t}")
		g.f("\tout := make([]%s, n)", h.goType)
		g.line("\tfor i := range out {")
		g.f("\t\tout[i] = %s", h.get)
		g.line("\t}")
		g.line("\treturn out, nil")
		g.line("}")
		g.line("")
	}
}
